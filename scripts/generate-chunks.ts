const TOPICS = [
  'daily_life',
  'work',
  'food',
  'travel',
  'shopping',
  'health',
  'opinions',
  'emotions',
  'technology',
  'formal_situations',
];

function levelRank(level: string) {
  return ['N5', 'N4', 'N3', 'N2', 'N1'].indexOf(level);
}

function main() {
  const chunks: Chunk[] = [];
  const seen = new Set<string>();

  for (const [noun, row] of Object.entries(NOUNS)) {
    for (const verbKey of row.verbs) {
      const verb = VERBS[verbKey];
      if (!verb || !verb.reading) continue;
      const particle = verb.particle ?? 'を';
      const phrase = `${noun}${particle}${verbKey}`;
      if (seen.has(phrase)) continue;
      seen.add(phrase);
      chunks.push({
        phrase,
        reading: `${row.reading}${particle}${verb.reading}`,
        meaning: `${verb.en} ${row.en}`,
        jlpt_level: levelRank(verb.jlpt) > levelRank(row.jlpt) ? verb.jlpt : row.jlpt,
        topic_tags: row.topics.filter((t) => TOPICS.includes(t)),
      });
    }
  }

  for (const p of SET_PHRASES) {
    if (!p.reading || !p.meaning) continue;
    if (seen.has(p.phrase)) continue;
    seen.add(p.phrase);
    chunks.push(p);
  }

  chunks.sort((a, b) => levelRank(a.jlpt_level) - levelRank(b.jlpt_level) || a.phrase.localeCompare(b.phrase, 'ja'));
  writeJson(path.join(process.cwd(), 'data', 'seed_chunks.json'), chunks);

  const byLevel: Record<string, number> = {};
  const byTopic: Record<string, number> = {};
  for (const c of chunks) {
    byLevel[c.jlpt_level] = (byLevel[c.jlpt_level] ?? 0) + 1;
    for (const t of c.topic_tags) byTopic[t] = (byTopic[t] ?? 0) + 1;
  }
  log(`generated ${chunks.length} seed chunks`);
  log(`  by level: ${JSON.stringify(byLevel)}`);
  log(`  by topic: ${JSON.stringify(byTopic)}`);
}

main();
